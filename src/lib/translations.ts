export function getCategoryLabel(categoryKey: string, lang: Language | string): string {
  const item = CATEGORY_TRANSLATIONS[categoryKey];
  if (!item) return categoryKey;
  return lang === 'en' ? item.en : item.ko;
}

export function getPriceLabel(priceKey: string, lang: Language | string): string {
  const item = PRICE_TRANSLATIONS[priceKey];
  if (!item) return priceKey;
  return lang === 'en' ? item.en : item.ko;
}

export function getToolDescription(tool: { description: string; descriptionEn?: string }, lang: Language | string): string {
  if (lang === 'en' && tool.descriptionEn) {
    return tool.descriptionEn;
  }
  return tool.description;
}

